    async def fetch_jobs(
        self,
        query: str = "",
        location: str = "",
        limit: int = 30,
        **kwargs: Any,
    ) -> list[dict[str, Any]]:
        """Return matching demo jobs (clearly labeled with provider='demo')."""
        results = self._demo_jobs
        if query:
            q = query.lower()
            results = [
                j for j in results
                if q in j["title"].lower()
                or q in j["company"].lower()
                or q in j["description"].lower()
                or any(q in s.lower() for s in (j.get("required_skills") or []))
            ]

        if location:
            loc = location.lower()
            results = [j for j in results if loc in j["location"].lower()]

        return results[:limit]
